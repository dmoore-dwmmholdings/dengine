#!/usr/bin/env python3
"""Generate PT's native Metal material seam using the installed pinned Slang library."""
import argparse
from pathlib import Path
import re,runpy,subprocess,tempfile
p=argparse.ArgumentParser();p.add_argument('--slang-lib',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[2]
driver=runpy.run_path(str(root/'tools/cook/importers/shader/regen_accel_shaders.py'))['DRIVER']
driver=driver.replace('spSetCodeGenTarget(request, hlsl ? SLANG_HLSL : SLANG_SPIRV);','spSetCodeGenTarget(request, SLANG_METAL);')
driver=driver.replace('spSetTargetProfile(request, 0, spFindProfile(session, hlsl ? "sm_5_0" : "spirv_1_5"));','')
driver=driver.replace('spAddPreprocessorDefine(request, hlsl ? "DE_ACCEL_FIXED_BINDINGS" : "DE_SHADER_TARGET_SPIRV", "1");','spAddPreprocessorDefine(request, "DE_SHADER_TARGET_METAL", "1");')
driver=driver.replace('"main", SLANG_STAGE_COMPUTE','"cs_pt_export", SLANG_STAGE_COMPUTE')
lib=a.slang_lib.resolve()
with tempfile.TemporaryDirectory(prefix='de-pt-') as t:
 t=Path(t);(t/'driver.cpp').write_text(driver)
 subprocess.run(['clang++','-std=c++17','-I'+str(root/'third_party/slang/include'),str(t/'driver.cpp'),str(lib),'-Wl,-rpath,'+str(lib.parent),'-o',str(t/'driver')],check=True)
 subprocess.run([str(t/'driver'),'metal','shaders/pathtracer/pt_accumulate.slang','shaders/common',str(t/'out')],cwd=root,check=True)
 s=re.sub(r'^#line.*\n','',(t/'out').read_text(),flags=re.M)
 for name in ['pt_camera_0(', 'pt_step_0(', 'de_rt_opacity_0(', 'struct PtParams_0','struct KernelContext_0']:
  if name not in s:raise RuntimeError('Slang ABI changed: '+name)
 # Stabilize only the generated adapter field names, never material math. Slang's numeric
 # disambiguators otherwise change when an unrelated local variable is added.
 mapping={}
 for struct,prefix in [('PtParams_0','ptp_'),('PtStep_0','pts_'),('DeRtRay_0','ptr_'),('DeRtHit_0','pth_'),('DeRtContext_0','ptq_'),('PtMediaParams_0','ptm_'),('PtPath_0','ptpath_'),('PtSssState_0','ptsss_'),('PtShadow_0','ptshadow_'),('PtLightProposal_0','ptlight_')]:
  body=re.search(r'struct '+struct+r'\s*\{([^}]+)\}',s).group(1)
  for name in re.findall(r'\b(\w+)\s*;',body):
   mapping[name]=prefix+re.sub(r'_\d+$','',name)
 s=re.sub(r'\b('+ '|'.join(mapping)+r')\b',lambda m:mapping[m.group()],s)
 (root/'shaders/pathtracer/pt_metal.generated').write_text('// Generated by regen_metal.py; shared Slang material math, do not edit.\n'+s)
