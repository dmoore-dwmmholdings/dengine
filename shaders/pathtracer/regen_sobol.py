#!/usr/bin/env python3
"""Generate PT's C direction matrices from pinned Joe-Kuo numeric data (stdlib only)."""
import argparse
import ast
import hashlib
from pathlib import Path
import runpy
import struct
import zipfile

ROOT = Path(__file__).resolve().parents[2]
DIMENSIONS = 1024
BITS = 32


def array(archive, name):
    data = archive.read(name + '.npy')
    if data[:6] != b'\x93NUMPY' or data[6] not in (1, 2):
        raise ValueError('unsupported numeric array header')
    width = 2 if data[6] == 1 else 4
    length = int.from_bytes(data[8:8 + width], 'little')
    offset = 8 + width + length
    header = ast.literal_eval(data[8 + width:offset].decode('ascii'))
    if header['descr'] != '<i8':
        raise ValueError('expected little-endian integers')
    count = 1
    for size in header['shape']:
        count *= size
    values = struct.unpack('<' + str(count) + 'q', data[offset:])
    shape = header['shape']
    if header['fortran_order'] and len(shape) == 2:
        values = tuple(values[row + column * shape[0]]
                       for row in range(shape[0]) for column in range(shape[1]))
    return shape, values


def generate():
    vendor = runpy.run_path(str(ROOT / 'tools/vendor/vendor.py'))
    config = vendor['load_toml'](str(ROOT / 'third_party/vendor.toml'))
    entry = next(item for item in config['lib'] if item['name'] == 'sobol')
    directory = ROOT / 'third_party/sobol'
    source = directory / entry['files'][0]
    with zipfile.ZipFile(source) as archive:
        _, poly = array(archive, 'poly')
        shape, initial = array(archive, 'vinit')
    table = []
    for dimension in range(DIMENSIONS):
        if dimension == 0:
            columns = [1 << (BITS - 1 - bit) for bit in range(BITS)]
        else:
            degree = poly[dimension].bit_length() - 1
            coefficients = (poly[dimension] ^ (1 << degree) ^ 1) >> 1
            columns = [initial[dimension * shape[1] + bit] << (BITS - 1 - bit)
                       for bit in range(degree)]
            for bit in range(degree, BITS):
                value = columns[bit - degree] ^ (columns[bit - degree] >> degree)
                for k in range(1, degree):
                    if (coefficients >> (degree - 1 - k)) & 1:
                        value ^= columns[bit - k]
                columns.append(value)
        table.extend(columns)
    pin = entry['url'].rsplit('/', 1)[1]
    output = ('/* Generated by shaders/pathtracer/regen_sobol.py.\n'
              ' * Joe-Kuo D(6) Sobol matrices: 1024 dimensions, 32 index bits.\n'
              ' * https://web.maths.unsw.edu.au/~fkuo/sobol/\n'
              f' * SciPy input snapshot: {pin}\n'
              f' * Input SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
              ' * Vendored input: third_party/sobol/scipy/stats/_sobol_direction_numbers.npz\n'
              ' * The engine has no SciPy/NumPy build or runtime dependency.\n */\n/*\n'
              + (directory / 'JOE_KUO_LICENSE').read_text()
              + '\nSciPy distribution licence:\n' + (directory / 'LICENSE').read_text()
              + '*/\n#ifndef DE_RENDER_PT_SOBOL_TABLE_H\n#define DE_RENDER_PT_SOBOL_TABLE_H\n'
              '#include <dengine/de_base.h>\n#define DE__PT_SOBOL_DIMENSIONS 1024u\n'
              '#define DE__PT_SOBOL_BITS 32u\n// clang-format off\n'
              'static const u32 de__pt_sobol_directions[1024 * 32] = {\n')
    for i in range(0, len(table), 8):
        output += '    ' + ', '.join(f'0x{x:08x}u' for x in table[i:i + 8]) + ',\n'
    return output + '};\n// clang-format on\n#endif\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'src/render/pathtracer/pt_sobol_table.h'
    output = generate()
    if args.check:
        if destination.read_text() != output:
            raise SystemExit('PT Sobol direction header is stale')
        print('PT Sobol direction header matches pinned numeric inputs')
    else:
        destination.write_text(output)


if __name__ == '__main__':
    main()
