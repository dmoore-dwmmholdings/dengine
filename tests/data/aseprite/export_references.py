"""Export owned source fixtures with Aseprite itself, or verify the checked-in provenance.

Run --aseprite /path/to/aseprite to regenerate; --build-provenance may record a source build.
CI runs --check without requiring Aseprite. These PNGs are never generated by DEngine.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile

CASES = [(name, None, name) for name in (
    "rgba", "indexed", "gray", "legacy6", "legacy8", "mixed-palette", "palette-packets",
    "nested", "group-flag", "z-order", "alpha", "group-order", "legacy-group-order",
    "indexed-background", "atlas", "atlas-grid", "playback", "deep",
    "background-opacity", "transparent-rgb")]
CASES += [("rgba", "Body", "rgba-body"), ("nested", "Red", "nested-red"),
          ("nested", "Green", "nested-green"), ("playback", "Body", "playback-body")]


def digest(filename):
    value = hashlib.sha256()
    with filename.open("rb") as stream:
        while data := stream.read(1024 * 1024):
            value.update(data)
    return value.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--aseprite", type=Path)
    parser.add_argument("--build-provenance", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    output = root / "reference"
    marker = output / "provenance.json"
    script = root / "export_reference.lua"
    if args.check:
        evidence = json.loads(marker.read_text())
        assert evidence["schema"] == 2
        assert evidence["exportMode"] == "Image.drawSprite RGBA compositor"
        assert evidence["scriptSha256"] == digest(script)
        assert evidence["tool"]["version"].startswith("Aseprite ")
        assert len(evidence["exports"]) == len(CASES)
        frames = 0
        for record, (name, layer, prefix) in zip(evidence["exports"], CASES):
            source = root / (name + ".aseprite")
            count = struct.unpack_from("<H", source.read_bytes(), 6)[0]
            groups = bool(struct.unpack_from("<I", source.read_bytes(), 14)[0] & 2)
            assert (record["fixture"], record["layer"], record["prefix"]) == (source.name, layer, prefix)
            assert record["sourceSha256"] == digest(source), source
            assert record["composeGroups"] == groups
            assert len(record["pngs"]) == count
            for i, png in enumerate(record["pngs"]):
                assert png["file"] == f"{prefix}-{i}.png"
                assert digest(output / png["file"]) == png["sha256"], png["file"]
            frames += count
        print(f"Verified {len(CASES)} real-Aseprite export sets / {frames} PNGs and all source/output hashes")
        return
    if not args.aseprite:
        parser.error("use --aseprite to export, or --check to verify checked-in data")
    # Preserve the upstream build/bin launcher path: resolving its macOS app-bundle
    # symlink changes application/data-path initialization even in batch mode.
    binary = args.aseprite.absolute()
    output.mkdir(exist_ok=True)
    exports = []
    logs = []
    # Never read or modify an artist's Aseprite preferences while producing test data.
    with tempfile.TemporaryDirectory(prefix="deng81-aseprite-profile-") as profile:
        environment = dict(os.environ, ASEPRITE_USER_FOLDER=profile)
        version = subprocess.run([str(binary), "--batch", "--version"], check=True,
                                 text=True, capture_output=True, env=environment,
                                 timeout=30).stdout.strip()
        assert version.startswith("Aseprite "), version
        tool = {"version": version, "binarySha256": digest(binary)}
        if args.build_provenance:
            build = json.loads(args.build_provenance.read_text())
            assert not build["sourcePatches"], "the reference tool's renderer must not be patched"
            tool["sourceBuild"] = {key: build[key] for key in (
                "version", "url", "sha256", "options", "sourcePatches")}
        export_cases(binary, root, output, script, environment, exports, logs)
    marker.write_text(json.dumps({"schema": 2, "exportMode": "Image.drawSprite RGBA compositor",
                                 "scriptSha256": digest(script), "tool": tool,
                                 "exports": exports}, indent=2) + "\n")
    print(f"Exported {len(exports)} sets with {version}; source/output hashes recorded")
    if any("Failure on line" in log for log in logs):
        print("Headless host emitted LaunchServices notification diagnostics; PNG export exited successfully")


def export_cases(binary, root, output, script, environment, exports, logs):
    for name, layer, prefix in CASES:
        source = root / (name + ".aseprite")
        count = struct.unpack_from("<H", source.read_bytes(), 6)[0]
        groups = bool(struct.unpack_from("<I", source.read_bytes(), 14)[0] & 2)
        command = [str(binary), "--batch", "--script-param", "source=" + str(source),
                   "--script-param", "output=" + str(output / prefix),
                   "--script-param", "groups=" + str(groups).lower()]
        if layer:
            command += ["--script-param", "layer=" + layer]
        command += ["--script", str(script)]
        result = subprocess.run(command, check=True, text=True, capture_output=True,
                                env=environment, timeout=30)
        logs.append(result.stdout + result.stderr)
        if "Warning:" in result.stdout or "Warning:" in result.stderr:
            raise RuntimeError("Aseprite source decode warning for " + name + ": " + result.stdout + result.stderr)
        pngs = []
        for i in range(count):
            filename = output / f"{prefix}-{i}.png"
            if not filename.is_file():
                raise RuntimeError("Aseprite did not export " + filename.name)
            pngs.append({"file": filename.name, "sha256": digest(filename)})
        exports.append({"fixture": source.name, "sourceSha256": digest(source),
                        "layer": layer, "prefix": prefix, "composeGroups": groups, "pngs": pngs})


if __name__ == "__main__":
    main()
