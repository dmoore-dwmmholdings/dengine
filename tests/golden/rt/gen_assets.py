#!/usr/bin/env python3
"""CC0 authored RT scenes; reuse the original DENG-307 primitive and texture assets by ID."""
import importlib.util
import math
from pathlib import Path
ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('gallery', ROOT.parent/'materials/assets/gen_assets.py')
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)
OUT = ROOT/'assets'
OUT.mkdir(exist_ok=True)
MATS = {
 'white': dict(base_color=[.7,.7,.7],roughness=.65),
 'red': dict(base_color=[.7,.035,.025],roughness=.7),
 'green': dict(base_color=[.025,.65,.06],roughness=.7),
 'mirror': dict(base_color=[.95,.8,.5],metallic=1.,roughness=0.),
 'rough': dict(base_color=[.95,.8,.5],metallic=1.,roughness=.3),
 'gold': dict(base_color=[2.,1.,.15],unlit=True),
 'checker': dict(base_color=[.8,.8,.8],base_color_tex='tex/checker',unlit=True),
 'glass': dict(base_color=[1.,1.,1.],roughness=.03,transmission=1.,ior=1.5,thickness=.3,attenuation_color=[.65,.85,.7],attenuation_distance=1.),
 'leaf': dict(base_color=[.3,.8,.1],base_color_tex='tex/leaf',alpha_mode='mask',alpha_cutoff=.5,double_sided=True,roughness=.7),
 'emitter':dict(base_color=[.7,.7,.7],emissive=[8.,6.,3.],emissive_strength=1.,roughness=.7),
}
for name,kv in MATS.items():
 (OUT/'materials'/f'{name}.mat.toml').write_bytes(g.mat_file(name,kv))
def mesh(s,pos,scale,mat,model='box',rotation=(0.,0.,0.,1.)):
 s.entity([g.xf(pos,rotation,scale),('DeMeshRenderer',[('mesh',f'mesh/{model}#{model}'),('materials',['rtmat/'+mat]),('layer_mask',1),('cast_shadows',True),('visible_in_rt',True)])])
def light(s,kind,pos,intensity,color=(1.,1.,1.),rot=(0.,0.,0.,1.),radius=.06):
 s.entity([g.xf(pos,rot),('DeLight',[('kind',kind),('color',list(color)),('intensity',float(intensity)),('range',15.),('source_radius',radius),('cast_shadows',True)])])
def common(name,env=True):
 s=g.Scene(name)
 g.camera(s,(0.,-8.,4.8),25.,48.,0.)
 mesh(s,(0.,0.,-.15),(7.,7.,.3),'white')
 if env:g.environment(s,'env/sky',.3)
 return s
def sun(s): light(s,'DE_LIGHT_DIRECTIONAL',(0.,0.,6.),4.,rot=g.quat_mul(g.quat_axis((0.,0.,1.),-.5),g.quat_axis((1.,0.,0.),.55)),radius=.045)
scenes={}
s=common('rt_shadows_pole');sun(s);mesh(s,(0.,0.,1.),(.18,.18,2.),'red');scenes[s.title]=s
s=common('rt_restir_many_lights');mesh(s,(-2.,1.,1.),(.7,.7,2.),'red');mesh(s,(1.,1.,.6),(1.2,1.2,1.2),'green')
for i in range(512):
 x=(i%16-7.5)*.35;y=((i//16)%16-7.5)*.35;z=1.+(i//256)*1.5
 light(s,'DE_LIGHT_POINT',(x,y,z),.8,(.4+(i%3)*.3,.4+((i+1)%3)*.3,.4+((i+2)%3)*.3))
scenes[s.title]=s
s=common('rt_ao_corner');mesh(s,(-2.,.5,1.5),(.2,5.,3.),'red');mesh(s,(0.,2.,1.5),(4.,.2,3.),'green');mesh(s,(0.,0.,.4),(.8,.8,.8),'white');scenes[s.title]=s
s=common('rt_reflections_mirror_rough');sun(s);mesh(s,(-1.6,0.,.08),(2.8,3.5,.12),'mirror');mesh(s,(1.6,0.,.08),(2.8,3.5,.12),'rough');mesh(s,(0.,1.,2.5),(2.,.3,1.3),'gold');mesh(s,(1.3,.2,.8),(1.2,1.2,1.2),'rough','sphere');scenes[s.title]=s
s=common('rt_gi_cornell',False);mesh(s,(-2.,0.,1.6),(.15,4.,3.2),'red');mesh(s,(2.,0.,1.6),(.15,4.,3.2),'green');mesh(s,(0.,2.,1.6),(4.,.15,3.2),'white');mesh(s,(0.,0.,3.2),(4.,4.,.1),'white');mesh(s,(0.,0.,3.1),(.8,.8,.1),'emitter');mesh(s,(-.7,0.,.5),(.8,.8,1.),'white');light(s,'DE_LIGHT_POINT',(0.,0.,2.7),120.,(1.,.85,.7));s.entity([g.xf((0.,0.,1.5)),('DeIrradianceVolume',[('extent',[2.,2.,1.5]),('counts',[3,3,3]),('intensity',1.),('blend_distance',.1)])]);scenes[s.title]=s
s=common('rt_refraction_glass');sun(s);mesh(s,(0.,0.,1.),(2.,2.,2.),'glass','sphere');mesh(s,(0.,2.,1.4),(4.,.2,2.8),'checker');mesh(s,(1.,1.3,.8),(.8,.6,1.6),'gold');scenes[s.title]=s
s=common('rt_foliage_shadow');sun(s)
for i in range(4):mesh(s,((i-1.5)*.8,.3,1.+.1*i),(1.2,1.2,1.2),'leaf','card',g.quat_axis((1.,0.,0.),-.3))
scenes[s.title]=s
manifest=['# CC0 procedural RT scenes, generated by ../gen_assets.py. Original S14 asset IDs reused.','[project]','asset_root="../.."','[assets]']
manifest += ['"env/sky"={type="texture",source="materials/assets/env/sky.exr",usage="environment",env_size=32,env_samples=256,compression="none"}',
 '"tex/checker"={type="texture",source="materials/assets/textures/checker.png"}',
 '"tex/leaf"={type="texture",source="materials/assets/textures/leaf.png"}']
for n in MATS:manifest.append(f'"rtmat/{n}"={{type="material",source="rt/assets/materials/{n}.mat.toml"}}')
for n,s in scenes.items():
 (OUT/f'{n}.scene.toml').write_bytes(s.text())
 manifest.append(f'"rt/{n}"={{type="scene",source="rt/assets/{n}.scene.toml"}}')
(OUT/'assets.toml').write_text('\n'.join(manifest)+'\n')
