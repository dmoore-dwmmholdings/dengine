"""Build-time artwork only; runtime needs neither CoreText nor font files.
Run on macOS with NumPy, SciPy and Pillow. The input Onest v11 is already pinned by DIDE.
"""
from pathlib import Path
import argparse, hashlib, re, subprocess, tempfile
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt, gaussian_filter

parser = argparse.ArgumentParser()
parser.add_argument('--font', type=Path, required=True)
parser.add_argument('--dide', type=Path, required=True)
a = parser.parse_args()
assert hashlib.sha256(a.font.read_bytes()).hexdigest() == '052df74533250c2e0ca0c4bdd32de594e107d99c1648e63820ef9c6142067828'
root = Path(__file__).resolve().parents[2]
with tempfile.TemporaryDirectory() as tmp:
    work = Path(tmp)
    subprocess.run(['swift', '-module-cache-path', '/private/tmp/dengine-swift-module-cache', str(root/'tools/branding/splash_type.swift'), str(a.font), str(work)], check=True)
    mask = np.asarray(Image.open(work/'emblem.png').convert('L'))
    distance = gaussian_filter(distance_transform_edt(mask < 128) - distance_transform_edt(mask >= 128), 1.15)
    encoded = np.round(np.clip(distance / 64 * .5 + .5, 0, 1) * 65535).astype(np.uint16)
    atlas = np.zeros((768, 512, 4), dtype=np.uint8)
    atlas[:, :, 3] = 255
    atlas[:, :, :2] = 255
    atlas[:512, :, 0] = encoded >> 8
    atlas[:512, :, 1] = encoded & 255
    atlas[512:640, :, 2] = np.asarray(Image.open(work/'wordmark.png').convert('L'))
    atlas[640:768, :, 2] = np.asarray(Image.open(work/'caption.png').convert('L'))
    target = root/'src/host/branding/brand-atlas.png'
    Image.fromarray(atlas).save(target, optimize=True)
data = target.read_bytes()
header = '/* Generated by tools/branding/generate_splash.py; Onest v11 (OFL). */\nstatic const unsigned char de__splash_atlas_png[] = {\n'
header += '\n'.join('    ' + ','.join(f'0x{x:02x}' for x in data[i:i+20]) + ',' for i in range(0,len(data),20))
header += '\n};\n'
(root/'src/host/branding/splash_atlas.h').write_text(header)
body = (root/'shaders/startup/brand_body.slang').read_text()
# The body uses only a small shared scalar/vector dialect. Keep the integer ray-step loop.
glsl = body.replace('[loop]', '').replace('for(int i=0;i<70;i++)', 'RAY_LOOP')
glsl = re.sub(r'\bfloat([234])\b', r'vec\1', glsl)
glsl = re.sub(r'\blerp\b', 'mix', glsl)
glsl = re.sub(r'(?<![\w.])\d+(?![\w.])', lambda m: m[0]+'.0', glsl).replace('RAY_LOOP', 'for(int i=0;i<70;i++)')
prefix = '''#version 300 es
// Generated from shaders/startup/brand_body.slang. Do not edit this copy.
precision highp float;
precision highp sampler2D;
struct BrandData {float width;float height;float time;float alpha;float text_alpha;};
uniform sampler2D atlas;
uniform vec4 frame;
uniform float textAlpha;
in vec2 texcoord;
out vec4 outputColor;
float saturate(float v){return clamp(v,0.,1.);}
vec4 brandAtlas(vec2 uv,BrandData p){return texture(atlas,uv);}
'''
suffix = '''
vec3 srgb(vec3 c){return mix(12.92*c,1.055*pow(max(c,vec3(0)),vec3(1./2.4))-.055,step(vec3(.0031308),c));}
void main(){BrandData p=BrandData(frame.x,frame.y,frame.z,frame.w,textAlpha);vec4 c=brandPixel(texcoord,p);outputColor=vec4(srgb(c.rgb),1);}
'''
(a.dide/'ui/src/startup/brand.frag.glsl').write_text(prefix+glsl+suffix)
(a.dide/'ui/src/startup/brand-atlas.png').write_bytes(data)
print(f'Atlas {len(data)} bytes; native and browser shader assets generated.')
