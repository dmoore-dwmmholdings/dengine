#!/usr/bin/env python3
"""Generate Unicode15.1 properties for UAX14 and emergency grapheme boundaries.

No host Unicode library is used. Inputs are pinned by third_party/vendor.toml.
"""
from pathlib import Path
import argparse

LB = 'XX AI AK AL AP AS B2 BA BB BK CB CJ CL CM CP CR EB EM EX GL H2 H3 HL HY ID IN IS JL JT JV LF NL NS NU OP PO PR QU RI SA SG SP SY VF VI WJ ZW ZWJ'.split()
GB = 'Other CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark L V T LV LVT'.split()
INCB = {'Consonant': 1, 'Extend': 2, 'Linker': 3}
COUNT = 0x110000


def records(path):
    for line in path.read_text(encoding='utf8').splitlines():
        line = line.split('#')[0].strip()
        if line:
            yield [p.strip() for p in line.split(';')]


def span(value):
    ends = value.split('..')
    return range(int(ends[0], 16), int(ends[-1], 16) + 1)


def generate(data, output):
    # Packed lb:6, grapheme:4, InCB:2, EAW/Pi/Pf/mark/Cn/ExtPict:6.
    values = [1 << 16] * COUNT
    for row in records(data / 'LineBreak.txt'):
        for cp in span(row[0]):
            values[cp] |= LB.index(row[1])
    for row in records(data / 'EastAsianWidth.txt'):
        if row[1] in ('F', 'W', 'H'):
            for cp in span(row[0]):
                values[cp] |= 1 << 12
    first = None
    for row in records(data / 'UnicodeData.txt'):
        cp, name, category = int(row[0], 16), row[1], row[2]
        if name.endswith(', First>'):
            first = cp
            continue
        start = first if name.endswith(', Last>') else cp
        first = None
        flags = ((category == 'Pi') << 13) | ((category == 'Pf') << 14) | ((category in ('Mn', 'Mc')) << 15)
        for code in range(start, cp + 1):
            values[code] = (values[code] & ~(1 << 16)) | flags
    for row in records(data / 'auxiliary/GraphemeBreakProperty.txt'):
        for cp in span(row[0]):
            values[cp] |= GB.index(row[1]) << 6
    for row in records(data / 'DerivedCoreProperties.txt'):
        if row[1] == 'InCB' and row[2] in INCB:
            for cp in span(row[0]):
                values[cp] |= INCB[row[2]] << 10
    for row in records(data / 'emoji/emoji-data.txt'):
        if row[1] == 'Extended_Pictographic':
            for cp in span(row[0]):
                values[cp] |= 1 << 17
    ranges = []
    start = 0
    for cp in range(1, COUNT + 1):
        if cp == COUNT or values[cp] != values[start]:
            ranges.append((start, cp - 1, values[start]))
            start = cp
    lines = ['/* Generated by tools/unicode/gen_linebreak.py; Unicode15.1.0. Do not edit. */',
             '#include "layout_internal.h"',
             'typedef struct de__unicode_range { u32 first, last, value; } de__unicode_range;',
             'static const de__unicode_range ranges[] = {']
    lines += ['    {0x%Xu, 0x%Xu, 0x%Xu},' % entry for entry in ranges]
    lines += ['};', '''de__unicode_props de__text_unicode(u32 cp) {
    u32 lo = 0, hi = (u32)(sizeof ranges / sizeof ranges[0]);
    while (lo < hi) {
        u32 mid = lo + (hi - lo) / 2;
        if (cp < ranges[mid].first) hi = mid;
        else if (cp > ranges[mid].last) lo = mid + 1;
        else {
            u32 v = ranges[mid].value;
            return (de__unicode_props){(u8)(v & 63u), (u8)((v >> 6) & 15u),
                (u8)((v >> 10) & 3u), (v & (1u << 12)) != 0, (v & (1u << 13)) != 0,
                (v & (1u << 14)) != 0, (v & (1u << 15)) != 0,
                (v & (1u << 16)) != 0, (v & (1u << 17)) != 0};
        }
    }
    return (de__unicode_props){.unassigned = true};
}''']
    output.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'{len(ranges)} ranges -> {output}')


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=root / 'third_party/unicode/unicodetools/data/ucd/dev')
    parser.add_argument('--out', type=Path, default=root / 'src/text/layout/linebreak_tables.c')
    args = parser.parse_args()
    generate(args.data, args.out)
