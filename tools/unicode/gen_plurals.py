#!/usr/bin/env python3
"""Generate deterministic cardinal CLDR rules and selected locale number/date records.
No timestamps/network. Run from any directory; XML sources are pinned by vendor.toml.
"""
import argparse,json,re,xml.etree.ElementTree as ET
from decimal import Decimal
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
CATS=['zero','one','two','few','many','other']
def atom(text):
    m=re.fullmatch(r'([nivwftec])(?:\s*%\s*(\d+))?\s*(=|!=|is not|is|not within|within|not in|in)\s*(.+)',text.strip())
    if not m: raise ValueError(text)
    operand,mod,op,ranges=m.groups();operand='e' if operand=='c' else operand
    x='o->'+operand
    if mod:x=f'fmod({x}, {mod}.0)'
    terms=[]
    for item in ranges.split(','):
        ends=item.strip().split('..')
        if len(ends)==1:terms.append(f'({x} == {ends[0]}.0)')
        else:
            term=f'({x} >= {ends[0]}.0 && {x} <= {ends[1]}.0'
            if op not in ['within','not within']:term+=f' && floor({x}) == {x}'
            terms.append(term+')')
    result='('+' || '.join(terms)+')'
    return '!'+result if op in ['!=','is not','not in','not within'] else result

def expr(text):return ' || '.join('('+' && '.join(atom(a) for a in clause.split(' and '))+')' for clause in text.split(' or '))
def cstr(s):return json.dumps(s,ensure_ascii=False)
def generate(source):
    xml=ET.parse(source/'supplemental/plurals.xml').getroot()
    lines=['/* Generated by tools/unicode/gen_plurals.py from CLDR48; do not edit. */','#include "text/loc/loc_internal.h"','#include <math.h>','#include <string.h>']
    locale_rules=[];samples=[]
    for index,rules in enumerate(xml.findall('./plurals[@type="cardinal"]/pluralRules')):
        lines.append(f'static de__plural rule_{index}(const de__plural_operands *o) {{')
        lines.append('    (void)o;')
        for rule in rules:
            condition=(rule.text or '').split('@',1)[0].strip();cat=rule.attrib['count']
            if condition:lines.append(f'    if ({expr(condition)}) return DE__PLURAL_{cat.upper()};')
            for locale in rules.attrib['locales'].split():
                if locale in ['en','fr','ru','pl','ar','ja']:
                    samples.append((locale,cat,(rule.text or '').split('@',1)[1:] ))
        lines+=['    return DE__PLURAL_OTHER;','}']
        locale_rules.extend((l.replace('_','-').lower(),index) for l in rules.attrib['locales'].split())
    lines+=['de__plural de__loc_plural_generated(const char *locale, const de__plural_operands *o) {','    static const struct { const char *locale; de__plural (*rule)(const de__plural_operands *); } rules[] = {']
    lines += [f'        {{{cstr(l)}, rule_{n}}},' for l,n in sorted(locale_rules)]
    lines += ['    };','    char tag[64]; size_t n = strlen(locale); if(n >= sizeof tag) return DE__PLURAL_OTHER;','    for(size_t i=0;i<=n;++i) { char c=locale[i]; tag[i]=c==\'_\'?\'-\':c>=\'A\'&&c<=\'Z\'?c+32:c; }','    for (;;) {','        size_t lo=0, hi=sizeof rules/sizeof rules[0];','        while(lo<hi){size_t mid=lo+(hi-lo)/2;int c=strcmp(tag,rules[mid].locale);if(c==0)return rules[mid].rule(o);if(c<0)hi=mid;else lo=mid+1;}','        char *dash=strrchr(tag,\'-\');if(!dash)break;*dash=0;','    }','    return DE__PLURAL_OTHER;','}']
    return '\n'.join(lines)+'\n'

def number_data(source):
    locales=['en','de','fr','es','it','pt','pt-BR','nl','sv','pl','cs','ru','uk','tr','ar','he','hi','th','ja','ko','zh-Hans','zh-Hant']
    cache={}
    def tree(tag):
        tag=tag.replace('-','_')
        if tag not in cache:
            p=source/'main'/f'{tag}.xml';cache[tag]=ET.parse(p).getroot() if p.exists() else None
        return cache[tag]
    def get(tag,path,fallback):
        tags=[];t=tag.replace('-','_')
        if t=='pt_BR':t='pt'
        while t:tags.append(t);t=t.rsplit('_',1)[0] if '_' in t else ''
        tags+=['root']
        for t in tags:
            tr=tree(t);element=tr.find(path) if tr is not None else None
            if tr is not None and path.endswith('/decimalFormat/pattern'):
                element=next((e for e in tr.findall(path) if 'type' not in e.attrib and 'count' not in e.attrib),None)
            if element is not None and element.text and element.text!='↑↑↑':return element.text
        return fallback
    lines=['/* Generated by gen_plurals.py from pinned CLDR48 selected locales. */','#include "text/loc/loc_internal.h"','#include <string.h>','static const de__loc_number_data data[] = {']
    for locale in locales:
        symbols='./numbers/symbols[@numberSystem="latn"]/'
        decimal=get(locale,symbols+'decimal','.');group=get(locale,symbols+'group',',')
        percent=get(locale,'./numbers/percentFormats[@numberSystem="latn"]/percentFormatLength/percentFormat/pattern','#,##0%')
        pattern=get(locale,'./numbers/decimalFormats[@numberSystem="latn"]/decimalFormatLength/decimalFormat/pattern','#,##0.###').split('.')[0]
        chunks=pattern.split(',');primary=len(chunks[-1]) if len(chunks)>1 else 0;secondary=len(chunks[-2]) if len(chunks)>2 else primary
        date='./dates/calendars/calendar[@type="gregorian"]/dateFormats/dateFormatLength[@type="%s"]/dateFormat/pattern'
        short=get(locale,date%'short','y-MM-dd');medium=get(locale,date%'medium','MMM d, y')
        months=[get(locale,f'./dates/calendars/calendar[@type="gregorian"]/months/monthContext[@type="format"]/monthWidth[@type="abbreviated"]/month[@type="{i}"]',str(i)) for i in range(1,13)]
        fields=[locale,decimal,group,percent,short,medium]
        lines.append('    {'+', '.join(cstr(x) for x in fields)+', {'+', '.join(cstr(x) for x in months)+f'}}, {primary}, {secondary}'+'},')
    lines+=['};','const de__loc_number_data *de__loc_number_data_get(const char *locale) {','    char tag[64];size_t n=strlen(locale);if(n>=sizeof tag)return &data[0];memcpy(tag,locale,n+1);','    for(;;){for(size_t i=0;i<sizeof data/sizeof data[0];++i)if(strcmp(tag,data[i].locale)==0)return &data[i];char *p=strrchr(tag,\'-\');if(!p)break;*p=0;}','    return &data[0];','}']
    return '\n'.join(lines)+'\n'

def sample_data(source):
    rows=[]
    for rules in ET.parse(source/'supplemental/plurals.xml').getroot().findall('./plurals[@type="cardinal"]/pluralRules'):
        for locale in rules.attrib['locales'].split():
            if locale not in ['en','fr','ru','pl','ar','ja']:continue
            for rule in rules:
                for section in (rule.text or '').split('@')[1:]:
                    body=section.split(' ',1)[1]
                    for item in body.split(','):
                        item=item.strip()
                        if not item or '…' in item:continue
                        ends=item.split('~');exponent=''
                        if len(ends)==1:values=[item]
                        else:
                            if 'c' in ends[0]:
                                a,e=ends[0].split('c');b,e2=ends[1].split('c');assert e==e2;exponent='c'+e
                            else:a,b=ends
                            scale=max(len(x.split('.')[1]) if '.' in x else 0 for x in [a,b]);step=Decimal(10)**(-scale)
                            first,last=Decimal(a),Decimal(b);assert (last-first)/step<10000
                            values=[format(first+step*i,f'.{scale}f')+exponent for i in range(int((last-first)/step)+1)]
                        rows.extend((locale,v,rule.attrib['count']) for v in values)
    return '/* Generated authoritative CLDR48 sample values, not rule expressions. */\nstatic const struct { const char *locale, *number; de__plural category; } cldr_samples[] = {\n'+''.join('    {'+cstr(l)+', '+cstr(v)+', DE__PLURAL_'+c.upper()+'},\n' for l,v,c in rows)+'};\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,default=ROOT/'third_party/cldr/common');p.add_argument('--out',type=Path,default=ROOT/'src/text/loc');a=p.parse_args();a.out.mkdir(parents=True,exist_ok=True)
    (a.out/'plural_rules_gen.c').write_text(generate(a.source),encoding='utf-8');(a.out/'number_data_gen.c').write_text(number_data(a.source),encoding='utf-8');(ROOT/'tests/unit/text/plural_samples_gen.h').write_text(sample_data(a.source),encoding='utf-8')
if __name__=='__main__':main()
