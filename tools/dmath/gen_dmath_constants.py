#!/usr/bin/env python3
"""Generates the constants of the deterministic math in src/core/math/dmath64.c (DENG-243).

Prints C source: the pi/2 splits for the Cody-Waite range reduction, the bits of 2/pi for the
Payne-Hanek reduction, the ln 2 split and the minimax polynomial coefficients (weighted Remez,
relative error). The coefficients are rounded to the nearest double; the printed hex literals are
what dmath64.c uses. Changing any of them changes results and needs a regenerated golden file
(tests/unit/math/vectors/dmath_golden.txt) with a reason in the commit message.

Needs mpmath (pip install mpmath). Usage: python3 tools/dmath/gen_dmath_constants.py
"""
import sys

try:
    import mpmath as mp
except ImportError:
    sys.exit("gen_dmath_constants.py needs mpmath: pip install mpmath")

mp.mp.dps = 90


def hexd(x):
    """Nearest double of x as a C99 hex literal."""
    return float(x).hex()


def split_bits(x, bits):
    """x truncated to `bits` significant bits (toward zero)."""
    e = int(mp.floor(mp.log(abs(x), 2)))
    scale = mp.mpf(2) ** (bits - 1 - e)
    return mp.floor(x * scale) / scale


def remez(f, w, a, b, deg, grid=4000, iters=40):
    """Coefficients c0..c_deg of the polynomial p(z) minimizing max |w(z) * (p(z) - f(z))| on
    [a, b], and that maximum. Classic Remez exchange on a dense grid."""
    n = deg + 1
    pts = [(a + b) / 2 - (b - a) / 2 * mp.cos(mp.pi * i / n) for i in range(n + 1)]
    xs = [a + (b - a) * (1 - mp.cos(mp.pi * i / grid)) / 2 for i in range(grid + 1)]
    fx = [f(x) for x in xs]
    wx = [w(x) for x in xs]
    coefs, err = None, None
    for _ in range(iters):
        rows, rhs = [], []
        for i, z in enumerate(pts):
            rows.append([z**j for j in range(n)] + [(-1) ** i / w(z)])
            rhs.append(f(z))
        sol = mp.lu_solve(mp.matrix(rows), mp.matrix(rhs))
        coefs = [sol[j] for j in range(n)]

        def e_at(k):
            return wx[k] * (mp.polyval(coefs[::-1], xs[k]) - fx[k])

        es = [e_at(k) for k in range(len(xs))]
        # Local extrema of the error on the grid, then one alternating extremum per sign run.
        ext = [0]
        for k in range(1, len(xs) - 1):
            if (es[k] - es[k - 1]) * (es[k + 1] - es[k]) <= 0:
                ext.append(k)
        ext.append(len(xs) - 1)
        runs = []
        for k in ext:
            if runs and mp.sign(es[k]) == mp.sign(es[runs[-1]]):
                if abs(es[k]) > abs(es[runs[-1]]):
                    runs[-1] = k
            else:
                runs.append(k)
        while len(runs) > n + 1:
            # Drop the smaller end.
            if abs(es[runs[0]]) < abs(es[runs[-1]]):
                runs.pop(0)
            else:
                runs.pop()
        err = max(abs(e) for e in es)
        if len(runs) < n + 1:
            break
        pts = [xs[k] for k in runs]
    return coefs, err


def report(name, coefs, err, fn_err=None):
    print(f"/* {name}: max weighted error {mp.nstr(err, 5)} (2^{mp.nstr(mp.log(err, 2), 4)})",
          end="")
    if fn_err is not None:
        print(f", after rounding to double 2^{mp.nstr(mp.log(fn_err, 2), 4)}", end="")
    print(" */")
    for i, c in enumerate(coefs):
        print(f"#define {name}{i} {hexd(c)} /* {mp.nstr(c, 20)} */")


def rounded_error(full, approx, a, b, samples=20000):
    worst = mp.mpf(0)
    for i in range(1, samples + 1):
        x = a + (b - a) * i / samples
        fx = full(x)
        if fx == 0:
            continue
        e = abs((approx(x) - fx) / fx)
        worst = max(worst, e)
    return worst


def main():
    pi = mp.pi
    pio2 = pi / 2

    print("/* ---- Generated by tools/dmath/gen_dmath_constants.py: do not edit by hand. ---- */")
    print()

    # Cody-Waite: pi/2 = P1 + P2 + P3 + P3T, P1..P3 with 33 significant bits each.
    p1 = split_bits(pio2, 33)
    p2 = split_bits(pio2 - p1, 33)
    p3 = split_bits(pio2 - p1 - p2, 33)
    p3t = pio2 - p1 - p2 - p3
    print("/* pi/2 = PIO2_1 + PIO2_2 + PIO2_3 + PIO2_3T; the first three have 33 bits. */")
    print(f"#define DE__PIO2_1  {hexd(p1)}")
    print(f"#define DE__PIO2_2  {hexd(p2)}")
    print(f"#define DE__PIO2_3  {hexd(p3)}")
    print(f"#define DE__PIO2_3T {hexd(p3t)}")
    hi = mp.mpf(float(pio2))
    print(f"#define DE__PIO2_HI {hexd(hi)}")
    print(f"#define DE__PIO2_LO {hexd(pio2 - hi)}")
    print(f"#define DE__INV_PIO2 {hexd(2 / pi)}")
    pi_hi = mp.mpf(float(pi))
    print(f"#define DE__PI_HI {hexd(pi_hi)}")
    print(f"#define DE__PI_LO {hexd(pi - pi_hi)}")
    pio4_hi = mp.mpf(float(pi / 4))
    print(f"#define DE__PIO4_HI {hexd(pio4_hi)}")
    print(f"#define DE__PIO4_LO {hexd(pi / 4 - pio4_hi)}")
    print()

    # Bits of 2/pi after the binary point, 32 per word, most significant first.
    words = 40
    with mp.workdps(words * 32 // 3 + 50):
        v = 2 / mp.pi
        out = []
        for _ in range(words):
            v *= 2**32
            d = int(mp.floor(v))
            out.append(d)
            v -= d
    print(f"/* 2/pi = 0.w[0] w[1] ... in base 2^32 ({words * 32} bits). */")
    print(f"static const u32 de__two_over_pi[{words}] = {{")
    for i in range(0, words, 6):
        print("    " + ", ".join(f"0x{w:08x}u" for w in out[i:i + 6]) + ",")
    print("};")
    print()

    ln2 = mp.log(2)
    l_hi = split_bits(ln2, 42)
    print("/* ln 2 = LN2_HI + LN2_LO; LN2_HI has 42 bits, so k * LN2_HI is exact for |k| < 2^11. */")
    print(f"#define DE__LN2_HI {hexd(l_hi)}")
    print(f"#define DE__LN2_LO {hexd(ln2 - l_hi)}")
    print(f"#define DE__INV_LN2 {hexd(1 / ln2)}")
    print()

    # sin(x) = x + x^3 * S(x^2), |x| <= pi/4 (+ a margin for the rounding of n in the reduction).
    xm = pi / 4 * (1 + mp.mpf(2) ** -20)
    zm = xm * xm

    def f_sin(z):
        if z == 0:
            return mp.mpf(-1) / 6
        x = mp.sqrt(z)
        return (mp.sin(x) - x) / (z * x)

    def w_sin(z):
        if z == 0:
            return mp.mpf(0) + mp.mpf(10) ** -40
        x = mp.sqrt(z)
        return z * x / mp.sin(x)

    c, e = remez(f_sin, w_sin, mp.mpf(0), zm, 5)
    cd = [mp.mpf(float(t)) for t in c]
    fe = rounded_error(mp.sin, lambda x: x + x**3 * mp.polyval(cd[::-1], x * x), 0, xm)
    report("DE__S", c, e, fe)
    print()

    # cos(x) = 1 - x^2/2 + x^4 * C(x^2).
    def f_cos(z):
        if z == 0:
            return mp.mpf(1) / 24
        x = mp.sqrt(z)
        return (mp.cos(x) - 1 + z / 2) / (z * z)

    def w_cos(z):
        if z == 0:
            return mp.mpf(10) ** -40
        x = mp.sqrt(z)
        return z * z / mp.cos(x)

    c, e = remez(f_cos, w_cos, mp.mpf(0), zm, 5)
    cd = [mp.mpf(float(t)) for t in c]
    fe = rounded_error(mp.cos, lambda x: 1 - x * x / 2 + x**4 * mp.polyval(cd[::-1], x * x), 0,
                       xm)
    report("DE__C", c, e, fe)
    print()

    # atan(u) = u + u^3 * A(u^2), |u| <= tan(pi/8).
    um = mp.tan(pi / 8) * (1 + mp.mpf(2) ** -20)

    def f_atan(z):
        if z == 0:
            return mp.mpf(-1) / 3
        u = mp.sqrt(z)
        return (mp.atan(u) - u) / (z * u)

    def w_atan(z):
        if z == 0:
            return mp.mpf(10) ** -40
        u = mp.sqrt(z)
        return z * u / mp.atan(u)

    c, e = remez(f_atan, w_atan, mp.mpf(0), um * um, 10)
    cd = [mp.mpf(float(t)) for t in c]
    fe = rounded_error(mp.atan, lambda u: u + u**3 * mp.polyval(cd[::-1], u * u), 0, um)
    report("DE__A", c, e, fe)
    print()

    # exp(r) = 1 + r + r^2 * E(r), |r| <= ln2/2.
    rm = ln2 / 2 * (1 + mp.mpf(2) ** -20)

    def f_exp(r):
        if r == 0:
            return mp.mpf(1) / 2
        return (mp.exp(r) - 1 - r) / (r * r)

    def w_exp(r):
        if r == 0:
            return mp.mpf(10) ** -40
        return r * r / mp.exp(r)

    c, e = remez(f_exp, w_exp, -rm, rm, 10)
    cd = [mp.mpf(float(t)) for t in c]
    fe = rounded_error(mp.exp, lambda r: 1 + r + r * r * mp.polyval(cd[::-1], r), -rm, rm)
    report("DE__E", c, e, fe)
    print()

    # log(m) = 2s + s^3 * L(s^2), s = (m - 1) / (m + 1), m in [sqrt(2)/2, sqrt(2)].
    sm = (mp.sqrt(2) - 1) / (mp.sqrt(2) + 1) * (1 + mp.mpf(2) ** -20)

    def f_log(z):
        if z == 0:
            return mp.mpf(2) / 3
        s = mp.sqrt(z)
        return (2 * mp.atanh(s) - 2 * s) / (z * s)

    def w_log(z):
        if z == 0:
            return mp.mpf(10) ** -40
        s = mp.sqrt(z)
        return z * s / (2 * mp.atanh(s))

    c, e = remez(f_log, w_log, mp.mpf(0), sm * sm, 7)
    cd = [mp.mpf(float(t)) for t in c]
    fe = rounded_error(lambda s: 2 * mp.atanh(s), lambda s: 2 * s + s**3 * mp.polyval(cd[::-1], s * s),
                       0, sm)
    report("DE__L", c, e, fe)


if __name__ == "__main__":
    main()
