#!/usr/bin/env python3
"""Regenerate the RHI's bootstrap translation shaders with the pinned Slang library.

Example: python3 tools/cook/importers/shader/regen_accel_shaders.py \
  --slang-lib build/dev/prebuilt/slang/lib/libslang-compiler.dylib
No shader compiler is loaded by the Vulkan runtime. Windows compiles the generated fixed-binding
HLSL with its inbox D3DCompiler on first use, independently of the optional DXIL cooker.
"""
import argparse
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile

DRIVER = r'''
#include "slang.h"
#include <cstdio>
#include <cstring>
int main(int argc, char **argv) {
    if (argc != 5) return 2;
    auto session = spCreateSession(nullptr);
    auto request = spCreateCompileRequest(session);
    bool hlsl = strcmp(argv[1], "hlsl") == 0;
    spSetCodeGenTarget(request, hlsl ? SLANG_HLSL : SLANG_SPIRV);
    spSetTargetProfile(request, 0, spFindProfile(session, hlsl ? "sm_5_0" : "spirv_1_5"));
    spAddPreprocessorDefine(request, hlsl ? "DE_ACCEL_FIXED_BINDINGS" : "DE_SHADER_TARGET_SPIRV", "1");
    spAddSearchPath(request, argv[3]);
    int unit = spAddTranslationUnit(request, SLANG_SOURCE_LANGUAGE_SLANG, nullptr);
    spAddTranslationUnitSourceFile(request, unit, argv[2]);
    spAddEntryPoint(request, unit, "main", SLANG_STAGE_COMPUTE);
    if (spCompile(request) < 0) {
        fputs(spGetDiagnosticOutput(request), stderr);
        return 1;
    }
    size_t size;
    const void *code = spGetEntryPointCode(request, 0, &size);
    FILE *out = fopen(argv[4], "wb");
    if (!out) return 2;
    bool ok = fwrite(code, 1, size, out) == size;
    fclose(out);
    spDestroyCompileRequest(request);
    spDestroySession(session);
    return ok ? 0 : 2;
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--slang-lib", type=Path, required=True)
    parser.add_argument("--cxx", default=os.environ.get("CXX", "clang++"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[4]
    library = args.slang_lib.resolve()
    with tempfile.TemporaryDirectory(prefix="de-accel-shaders-") as tmp:
        tmp = Path(tmp)
        driver, exe = tmp / "compile.cpp", tmp / "compile"
        driver.write_text(DRIVER)
        subprocess.run([args.cxx, "-std=c++17", "-I" + str(root / "third_party/slang/include"),
                        str(driver), str(library), "-Wl,-rpath," + str(library.parent),
                        "-o", str(exe)], check=True)
        for target in ("spirv", "hlsl"):
            subprocess.run([str(exe), target, "shaders/rhi/accel_instances.slang",
                            "shaders/common", str(tmp / target)], cwd=root, check=True)
        binary = (tmp / "spirv").read_bytes()
        words = struct.unpack("<%dI" % (len(binary) // 4), binary)
        text = "/* Generated by tools/cook/importers/shader/regen_accel_shaders.py. */\n"
        text += "static const u32 de__accel_instances_spirv[] = {\n"
        for offset in range(0, len(words), 8):
            text += "    " + ", ".join("0x%08xu" % w for w in words[offset:offset+8]) + ",\n"
        (root / "src/gpu/vulkan/vk_accel_shader.h").write_text(text + "};\n")
        text = "/* Generated by tools/cook/importers/shader/regen_accel_shaders.py. */\n"
        text += "static const char de__accel_instances_hlsl[] =\n"
        for line in (tmp / "hlsl").read_text().splitlines():
            if line.strip() and not line.startswith("#line"):
                text += "    " + json.dumps(line + "\n") + "\n"
        (root / "src/gpu/d3d12/d3d12_accel_shader.h").write_text(text + ";\n")


if __name__ == "__main__":
    main()
