#!/usr/bin/env python3
"""Regenerate Metal's shared RT opacity helpers using the pinned Slang compiler library.

The canonical material/UV/geometry logic remains shaders/rt/rt_opacity.slang. The native
trace_metal.metal adapter supplies only Metal's explicit IFT intersection invocation. No SDK
or compiler is downloaded. Example: --slang-lib build/dev/prebuilt/slang/lib/libslang-compiler.dylib
"""
import argparse
import os
from pathlib import Path
import re
import runpy
import subprocess
import tempfile


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--slang-lib', type=Path, required=True)
    p.add_argument('--cxx', default=os.environ.get('CXX', 'clang++'))
    a = p.parse_args()
    root = Path(__file__).resolve().parents[4]
    driver = runpy.run_path(str(Path(__file__).with_name('regen_accel_shaders.py')))['DRIVER']
    driver = driver.replace('spSetCodeGenTarget(request, hlsl ? SLANG_HLSL : SLANG_SPIRV);',
                            'spSetCodeGenTarget(request, SLANG_METAL);')
    driver = driver.replace('spSetTargetProfile(request, 0, spFindProfile(session, hlsl ? "sm_5_0" : "spirv_1_5"));', '')
    driver = driver.replace('spAddPreprocessorDefine(request, hlsl ? "DE_ACCEL_FIXED_BINDINGS" : "DE_SHADER_TARGET_SPIRV", "1");',
                            'spAddPreprocessorDefine(request, "DE_SHADER_TARGET_METAL", "1");')
    driver = driver.replace('    bool hlsl = strcmp(argv[1], "hlsl") == 0;', '')
    driver = driver.replace('"main", SLANG_STAGE_COMPUTE', '"cs_opacity_export", SLANG_STAGE_COMPUTE')
    library = a.slang_lib.resolve()
    with tempfile.TemporaryDirectory(prefix='de-rt-opacity-') as tmp:
        tmp = Path(tmp)
        (tmp/'driver.cpp').write_text(driver)
        subprocess.run([a.cxx, '-std=c++17', '-I'+str(root/'third_party/slang/include'),
                        str(tmp/'driver.cpp'), str(library), '-Wl,-rpath,'+str(library.parent),
                        '-o', str(tmp/'driver')], check=True)
        subprocess.run([str(tmp/'driver'), 'metal', 'shaders/rt/opacity_export.slang',
                        'shaders/common', str(tmp/'opacity.metal')], cwd=root, check=True)
        source = (tmp/'opacity.metal').read_text()
        # Slang's preservation entry can remain: it is not the pipeline entry or an IFT callback.
        # Pin the adapter seam explicitly rather than silently accepting renamed helper ABI.
        required = ['struct DeBindlessHeap_default_0', 'struct KernelContext_0',
                    'struct DeRtContext_0', 'bool de_rt_opacity_0(', 'de_heap_0', 'tlas_0', 'lods_1']
        for name in required:
            if name not in source:
                raise RuntimeError('Slang adapter ABI changed: '+name)
        source = re.sub(r'^#line.*\n', '', source, flags=re.MULTILINE)
        source = re.sub(r'\n{3,}', '\n\n', source)
        (root/'shaders/rt/rt_opacity_metal.generated').write_text(
            '// Generated by regen_rt_opacity.py from rt_opacity.slang; do not edit.\n'+source)


if __name__ == '__main__':
    main()
