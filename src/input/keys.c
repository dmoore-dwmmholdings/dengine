const char *de_key_name(de_key k) {
    if ((u32)k >= DE_KEY_COUNT_)
        return NULL;
    return k_key_names[k];
}

static char ascii_lower(char c) {
    return (c >= 'A' && c <= 'Z') ? (char)(c - 'A' + 'a') : c;
}

static bool name_eq(const char *table, const char *name) {
    for (;; ++table, ++name) {
        if (ascii_lower(*name) != *table)
            return false;
        if (*table == '\0')
            return true;
    }
}

de_key de_key_from_name(const char *name) {
    if (name == NULL || name[0] == '\0')
        return DE_KEY_UNKNOWN;
    /* A linear scan of a fixed table: binding files are parsed rarely, never per frame. */
    for (u32 k = 1; k < DE_KEY_COUNT_; ++k)
        if (k_key_names[k] != NULL && name_eq(k_key_names[k], name))
            return (de_key)k;
    return DE_KEY_UNKNOWN;
}
